/* SMOKE RUNNER — boots the production build, fetches every registered route,
   asserts its health markers, and (with --write) writes DOCS/HEALTH-REPORT.md.

   Usage:
     npm run build && npm run smoke           # check only
     npm run build && npm run docs:health     # check + write report
     node _build/smoke.mjs --base http://localhost:3000 [--write]  # reuse a server
*/

import { spawn } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const WRITE = args.includes("--write") || process.argv[1].includes("docs-health");
const baseArg = args.indexOf("--base");
const EXTERNAL_BASE = baseArg >= 0 ? args[baseArg + 1] : null;
const PORT = 3211;
const BASE = EXTERNAL_BASE ?? `http://localhost:${PORT}`;

let server = null;

async function waitForServer(url, tries = 60) {
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url, { cache: "no-store" });
      if (res.ok) return true;
    } catch {}
    await new Promise((r) => setTimeout(r, 1000));
  }
  return false;
}

async function main() {
  if (!EXTERNAL_BASE) {
    console.log(`▶ starting production server on :${PORT} …`);
    const nextBin = path.join(ROOT, "node_modules", "next", "dist", "bin", "next");
    server = spawn(process.execPath, [nextBin, "start", "-p", String(PORT)], {
      cwd: ROOT,
      stdio: ["ignore", "pipe", "pipe"],
    });
    server.stdout.on("data", () => {});
    server.stderr.on("data", (d) => {
      const s = String(d);
      if (s.toLowerCase().includes("error")) console.error(s.slice(0, 300));
    });
    const up = await waitForServer(`${BASE}/api/health`);
    if (!up) throw new Error("server did not come up in 60s — did you run `npm run build`?");
  }

  console.log(`▶ fetching registry from ${BASE}/api/registry`);
  const reg = await (await fetch(`${BASE}/api/registry`, { cache: "no-store" })).json();
  const routes = reg.routes;
  console.log(`▶ checking ${routes.length} routes …`);

  const results = [];
  for (const r of routes) {
    const url = `${BASE}${r.sample ?? r.path}`;
    const t0 = Date.now();
    try {
      const res = await fetch(url, { cache: "no-store" });
      const text = await res.text();
      const missing = r.expects.filter((m) => !text.includes(m));
      const ok = res.ok && missing.length === 0;
      results.push({ ...r, ok, status: res.status, ms: Date.now() - t0, detail: ok ? "markers present" : !res.ok ? `HTTP ${res.status}` : `missing "${missing[0]}"` });
      console.log(`  ${ok ? "✓" : "✗"} ${String(res.status).padEnd(3)} ${(Date.now() - t0 + "ms").padEnd(7)} ${r.sample ?? r.path}${ok ? "" : `  ← ${results.at(-1).detail}`}`);
    } catch (e) {
      results.push({ ...r, ok: false, status: 0, ms: Date.now() - t0, detail: String(e.message ?? e) });
      console.log(`  ✗ ERR ${r.sample ?? r.path} ← ${e.message}`);
    }
  }

  const pass = results.filter((r) => r.ok).length;
  const fail = results.length - pass;
  console.log(`\n▶ result: ${pass}/${results.length} routes healthy${fail ? ` — ${fail} FAILING` : " — ALL GREEN ✅"}`);

  if (WRITE) {
    mkdirSync(path.join(ROOT, "DOCS"), { recursive: true });
    const lines = [
      "# Supreme Suite — Health Report",
      "",
      `> Generated by \`npm run docs:health\` on ${new Date().toISOString()}`,
      `> **${pass}/${results.length} routes healthy** · ${reg.actions.length} action contracts · ${reg.workflows.length} workflows · ${reg.systems.length} systems`,
      "",
      "Interactive behavior checks (workflows, branding, AI booking, data round-trips) run live on [/status](/status) — this file covers route/SSR integrity.",
      "",
      "| ✓ | Route | Title | Group | HTTP | ms | Detail |",
      "|---|-------|-------|-------|------|----|--------|",
      ...results.map((r) => `| ${r.ok ? "✅" : "❌"} | \`${r.sample ?? r.path}\` | ${r.title} | ${r.group} | ${r.status} | ${r.ms} | ${r.detail} |`),
      "",
      "## Systems registered",
      "",
      ...reg.systems.map((s) => `- **${s.name}** (\`${s.slug}\`, ${s.category}) — ${s.pipeline.length} stages, ${s.modules.length} modules, plans from $${s.plans[0]?.monthly}/mo`),
      "",
    ];
    writeFileSync(path.join(ROOT, "DOCS", "HEALTH-REPORT.md"), lines.join("\n"));
    console.log("▶ wrote DOCS/HEALTH-REPORT.md");
  }

  if (server) server.kill();
  process.exit(fail ? 1 : 0);
}

main().catch((e) => {
  console.error("SMOKE FAILED:", e.message);
  if (server) server.kill();
  process.exit(1);
});
